"""core/schemas.py — SENTRY shared Pydantic v2 data contracts.

THIS FILE IS THE SINGLE SOURCE OF TRUTH FOR ALL INTER-STAGE DATA SHAPES.
Do NOT edit this file in any stage other than P0.  If a schema appears wrong,
raise a SCHEMA CHANGE REQUEST to the P0 owner.

Import convention for all other stages:
    from core.schemas import Chunk, EvidenceReport, DiagnosisResponse, ...
"""

from __future__ import annotations

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# Shared base — all SENTRY models inherit from this so serialisation settings
# are applied uniformly across every stage.
# ---------------------------------------------------------------------------


class _SentryBase(BaseModel):
    """Project-wide base: strict validation, no extra fields allowed."""

    model_config = {
        # Reject payloads that contain undeclared fields; catches typos early.
        "extra": "forbid",
        # Allow datetime objects to be used directly in JSON serialisation.
        "arbitrary_types_allowed": False,
        # Populate model fields by alias so JSON round-trips work cleanly.
        "populate_by_name": True,
    }


# ===========================================================================
# SECTION 1 — INGESTION / CORPUS MODELS
# ===========================================================================


class SafetyNote(_SentryBase):
    """A single safety statement extracted verbatim from a source document.

    Severity mirrors IEC/ANSI Z535 signal words; they map directly to the
    keyword regex used in R1.3.
    """

    text: str = Field(..., description="Verbatim safety sentence from the source document.")
    severity: Literal["danger", "warning", "caution", "notice"] = Field(
        ...,
        description="Signal-word severity level per IEC/ANSI Z535.",
    )


class Chunk(_SentryBase):
    """A retrievable document fragment produced by the S1 ingestion pipeline.

    chunk_id is deterministic: sha1(doc_id + section_path + chunk_index)[:12],
    so citations never rot when a document is re-ingested unchanged (R1.5).
    """

    chunk_id: str = Field(..., description="Deterministic 12-hex-char SHA-1 prefix.")
    doc_id: str = Field(..., description="Stable document identifier (slug, not a path).")
    doc_title: str = Field(..., description="Human-readable document title.")
    revision: str = Field(..., description='E.g. "Rev C, 2023-08".')
    section_path: list[str] = Field(
        ...,
        description="Ordered heading breadcrumb, outermost first.",
    )
    page_start: int = Field(..., ge=1, description="1-indexed starting page.")
    page_end: int = Field(..., ge=1, description="1-indexed ending page (inclusive).")
    text: str = Field(..., description="Raw extracted text of this chunk.")
    chunk_type: Literal["procedure", "description", "table", "warning"] = Field(
        ..., description="Structural classification used to weight retrieval."
    )
    has_safety: bool = Field(
        ..., description="True iff at least one SafetyNote was found in this chunk."
    )
    safety_notes: list[SafetyNote] = Field(
        default_factory=list,
        description="Verbatim safety sentences extracted from this chunk (R1.3).",
    )
    asset_class: str = Field(
        ..., description='Equipment class, e.g. "centrifugal_pump".'
    )
    applicable_models: list[str] = Field(
        default_factory=list,
        description="Model numbers this chunk applies to, e.g. [\"CP-450\", \"CP-460\"].",
    )
    token_count: int = Field(..., ge=0, description="Approximate token count for budget tracking.")


class ErrorCodeEntry(_SentryBase):
    """Structured row from the error-code side-table extracted during ingestion (R1.4).

    Looked up by exact match, never by fuzzy retrieval, to avoid hallucinated meanings.
    """

    code: str = Field(..., description='Machine error code, e.g. "E-204".')
    asset_class: str = Field(..., description="Equipment class this code applies to.")
    meaning: str = Field(..., description="Human-readable short description of the fault.")
    probable_causes: list[str] = Field(
        default_factory=list,
        description="Ordered list of probable causes from the OEM table.",
    )
    section_ref: str = Field(
        ...,
        description="Section heading or chunk_id where the error code is defined.",
    )


# ===========================================================================
# SECTION 2 — EVIDENCE MODELS  (S2 output contract)
# ===========================================================================


class SensorReading(_SentryBase):
    """A single raw sensor value as supplied in the /v1/diagnose request payload."""

    name: str = Field(..., description="Sensor identifier matching the asset's baseline config.")
    value: float = Field(..., description="Measured value in the reported unit.")
    unit: str = Field(..., description='Physical unit string, e.g. "C", "mm/s", "bar".')
    status: Literal["ok", "missing", "stale"] = Field(
        default="ok",
        description="Data-quality flag; stale means outside the freshness window (R2.8).",
    )
    last_seen: datetime | None = Field(
        default=None,
        description="UTC timestamp of the reading; None only when status=='missing'.",
    )


class Deviation(_SentryBase):
    """Quantified deviation for one sensor, as computed by the S2 Evidence Engine.

    All numeric fields are computed deterministically by S2 — the LLM never
    touches these values (R2.3, R5.2).
    """

    sensor: str = Field(..., description="Sensor identifier.")
    value: float = Field(..., description="Measured value.")
    unit: str = Field(..., description="Physical unit.")
    nominal: float = Field(..., description="Nominal (expected) value from the baseline config.")
    normal_range: tuple[float, float] = Field(
        ..., description="[low, high] bounds of the normal operating band."
    )
    delta: float = Field(..., description="value − nominal; signed.")
    pct_dev: float = Field(..., description="delta / nominal; signed fraction.")
    z_score: float = Field(..., description="Standard-score (robust MAD variant for vibration).")
    band: Literal["normal", "warn", "alarm", "out_of_range"] = Field(
        ..., description="Operating band classification (R2.3)."
    )
    severity: float = Field(
        ..., ge=0, le=100, description="Severity score 0-100, monotonic in |z| and band (R2.4)."
    )
    trend: Literal["rising", "falling", "stable", "unknown"] = Field(
        ..., description="Direction of recent change (EWMA slope sign)."
    )
    roc_per_min: float | None = Field(
        default=None,
        description="Rate of change per minute; None if no time series was supplied.",
    )
    source: str = Field(
        ...,
        description='Baseline provenance: "oem_config" or "learned_baseline".',
    )


class Signature(_SentryBase):
    """A cross-sensor pattern match from declarative YAML correlation rules (R2.5).

    Explicitly labelled as a heuristic hint to the retriever, never as fact.
    """

    name: str = Field(..., description='Pattern name, e.g. "bearing_distress".')
    confidence: float = Field(..., ge=0.0, le=1.0, description="Rule-computed confidence [0, 1].")
    rule_id: str = Field(..., description='Rule identifier from the YAML corpus, e.g. "R-014".')
    basis: list[str] = Field(
        ..., description="Sensor names that triggered this rule."
    )


class HistoryFeatures(_SentryBase):
    """Maintenance history features extracted for this asset (R2.7)."""

    days_since_service: int = Field(
        ..., ge=0, description="Calendar days since the last recorded service event."
    )
    same_code_90d: int = Field(
        ..., ge=0, description="Count of occurrences of the same error code in the last 90 days."
    )
    recent_parts: list[str] = Field(
        default_factory=list,
        description="Parts replaced at the last service event.",
    )


class ErrorCodeResult(_SentryBase):
    """Outcome of an exact-match error-code lookup (R2.6).

    'absent' means no error code was submitted; 'unrecognized' triggers refusal.
    """

    code: str | None = Field(default=None, description="The submitted error code, or None.")
    meaning: str | None = Field(
        default=None,
        description="OEM-defined meaning; None if unrecognized or absent.",
    )
    status: Literal["recognized", "unrecognized", "absent"] = Field(
        ..., description="Lookup result; 'unrecognized' is a refusal trigger (R2.6)."
    )


class EvidenceReport(_SentryBase):
    """Complete output of the S2 Evidence Engine for one diagnostic request.

    This is the primary input to S3 (Retrieval) and S5 (Synthesis).
    """

    asset_id: str = Field(..., description="Asset identifier from the request.")
    asset_class: str = Field(..., description='Equipment class, e.g. "centrifugal_pump".')
    captured_at: datetime = Field(..., description="Timestamp of the sensor snapshot.")
    error_code: ErrorCodeResult = Field(..., description="Error-code lookup result.")
    deviations: list[Deviation] = Field(
        default_factory=list,
        description="Sensors whose values exceed normal-band thresholds, sorted by severity desc.",
    )
    normal_sensors: list[str] = Field(
        default_factory=list,
        description="Sensor names whose readings are within the normal band.",
    )
    missing_sensors: list[str] = Field(
        default_factory=list,
        description="Sensors with status=='missing' or 'stale' (R2.8).",
    )
    signatures: list[Signature] = Field(
        default_factory=list,
        description="Cross-sensor patterns matched by correlation rules (R2.5).",
    )
    history_features: HistoryFeatures = Field(
        ..., description="Maintenance history features for this asset."
    )


# ===========================================================================
# SECTION 3 — RETRIEVAL MODELS  (S3 output contract)
# ===========================================================================


class RetrievedChunk(_SentryBase):
    """A chunk returned by the retrieval stage, decorated with scoring metadata."""

    chunk: Chunk = Field(..., description="The retrieved chunk payload.")
    sparse_score: float | None = Field(
        default=None, description="BM25 / TF-IDF score; None if sparse retrieval was skipped."
    )
    dense_score: float | None = Field(
        default=None, description="Dense embedding cosine score; None if dense retrieval was skipped."
    )
    fused_score: float | None = Field(
        default=None, description="RRF-fused score after hybrid merge; None if not applicable."
    )
    rerank_score: float | None = Field(
        default=None, description="Cross-encoder rerank score; None if reranker was not run."
    )
    retrieved_by: list[str] = Field(
        default_factory=list,
        description='Which sub-retrievers surfaced this chunk, e.g. ["sparse", "dense"].',
    )
    forced_safety_include: bool = Field(
        default=False,
        description="True iff this chunk was force-included because it contains a safety note "
        "relevant to the query (R5.5 safety sweep).",
    )


class RetrievalTrace(_SentryBase):
    """Low-level trace from a single retrieval sub-system for debugging / ablation."""

    query_text: str = Field(..., description="The query string sent to this retriever.")
    engine: str = Field(..., description='Retriever name, e.g. "bm25", "dense", "tfidf".')
    top_k: int = Field(..., ge=1, description="Number of results requested from this engine.")
    raw_results: list[tuple[str, float]] = Field(
        default_factory=list,
        description="(chunk_id, score) pairs in rank order from this engine.",
    )


class RetrievalResult(_SentryBase):
    """Complete output of the S3 Retrieval stage for one diagnostic request."""

    status: Literal["sufficient", "insufficient"] = Field(
        ...,
        description=(
            "'insufficient' triggers the refusal path in S5 (R5.6). "
            "Sufficiency is determined by whether best_score >= relevance_floor."
        ),
    )
    chunks: list[RetrievedChunk] = Field(
        default_factory=list,
        description="Final ranked list of chunks to be passed to S5.",
    )
    traces: list[RetrievalTrace] = Field(
        default_factory=list,
        description="Per-engine traces for ablation analysis and debugging.",
    )
    best_score: float = Field(
        ..., description="Highest fused (or rerank) score among the retrieved chunks."
    )


