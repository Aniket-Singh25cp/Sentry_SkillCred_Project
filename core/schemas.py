# SECTION 4 — ANOMALY MODEL  (S4 output contract, feature-flagged)
# ===========================================================================


class AnomalyResult(_SentryBase):
    """Output from the optional S4 anomaly detection model (use_anomaly_model flag).

    When the flag is False this model is never instantiated; S5 proceeds without it.
    """

    model_version: str = Field(..., description="MLflow artifact version or semver of the model.")
    anomaly_score: float = Field(
        ..., ge=0.0, le=1.0, description="Normalised anomaly score in [0, 1]."
    )
    is_anomalous: bool = Field(..., description="True iff anomaly_score exceeds the model's threshold.")
    feature_attributions: dict[str, float] = Field(
        default_factory=dict,
        description="SHAP values keyed by sensor name; empty dict if SHAP was not run.",
    )


# ===========================================================================
# SECTION 5 — SYNTHESIS / OUTPUT MODELS  (S5 output contract)
# ===========================================================================


class Citation(_SentryBase):
    """A resolvable pointer back to a specific page in a specific document revision.

    Every citation must be validatable against the chunk store (R5.4).
    """

    chunk_id: str = Field(..., description="chunk_id of the source chunk.")
    doc_title: str = Field(..., description="Document title for display.")
    revision: str = Field(..., description="Document revision string.")
    section: str = Field(..., description="Section heading or section_path joined as a string.")
    page: int = Field(..., ge=1, description="Page number within the source document.")


class MeasuredFact(_SentryBase):
    """A single quantitative fact copied programmatically from the EvidenceReport.

    The LLM never generates these numbers; it is only permitted to reference
    pre-computed values (R5.2).
    """

    statement: str = Field(
        ...,
        description="Human-readable statement of the measured fact.",
    )
    source: str = Field(
        ...,
        description='Provenance label, e.g. "sensor_engine" or "error_code_lookup".',
    )
    sensor: str | None = Field(
        default=None,
        description="Sensor name, if the fact originates from a sensor reading.",
    )


class ManualInstruction(_SentryBase):
    """A single procedural step derived verbatim or minimally paraphrased from a document (R5.2).

    Any step where verbatim_safety==True MUST preserve the exact safety text
    from the source chunk's safety_notes (R5.5).
    """

    step: str = Field(
        ...,
        description="Instruction text; safety sentences must be verbatim substrings of source.",
    )
    verbatim_safety: bool = Field(
        ...,
        description="True iff this step contains a safety sentence that must appear verbatim.",
    )
    citation: Citation = Field(..., description="Source citation for the guardrail resolver.")


class ChecklistStep(_SentryBase):
    """One step in the ranked inspection checklist (R5.3).

    Ordering rule: safety/isolation first, then non-invasive observation, then
    low-cost checks, then invasive disassembly.  This ordering is enforced in
    post-processing, not generated by the model.
    """

    order: int = Field(..., ge=1, description="1-based position in the final ordered checklist.")
    action: str = Field(..., description="The action the technician must perform.")
    expected_observation: str = Field(
        ..., description="What a passing outcome looks like."
    )
    if_abnormal_then: str = Field(
        ..., description="Escalation or branching instruction if the observation fails."
    )
    tools_required: list[str] = Field(
        default_factory=list,
        description="Tools and PPE needed for this step.",
    )
    est_minutes: int = Field(..., ge=0, description="Estimated elapsed time in minutes.")
    is_safety_critical: bool = Field(
        ..., description="True iff this step involves energy isolation, LOTO, or PPE."
    )
    citation: Citation = Field(..., description="Mandatory resolvable citation (R5.4).")


class Hypothesis(_SentryBase):
    """One ranked probable root cause produced by S5 (R5.2, R5.10).

    Confidence buckets are derived from retrieval scores + deviation severity
    in code, not freely generated by the LLM.
    """

    rank: int = Field(..., ge=1, description="Ordinal rank; 1 = most probable.")
    cause: str = Field(..., description="Human-readable description of the probable cause.")
    confidence: Literal["high", "medium", "low"] = Field(
        ..., description="Bucket derived from rerank score + deviation severity (R5.10)."
    )
    confidence_score: float = Field(
        ..., ge=0.0, le=1.0, description="Numeric confidence used to compute the bucket."
    )
    supporting_sensors: list[str] = Field(
        default_factory=list,
        description="Sensor names whose deviations support this hypothesis.",
    )
    supporting_chunks: list[str] = Field(
        default_factory=list,
        description="chunk_ids whose content supports this hypothesis.",
    )
    discriminating_check: str = Field(
        ...,
        description="The single test or observation that would confirm or refute this hypothesis.",
    )


class Refusal(_SentryBase):
    """Structured refusal payload emitted when SENTRY cannot safely answer (R5.6).

    A refusal is not an error; it is a safety-correct outcome that tells the
    technician exactly what the system could not do and what to do instead.
    """

    reason: Literal[
        "no_relevant_evidence",
        "unrecognized_code",
        "guardrail_block",
        "schema_failure",
    ] = Field(..., description="Machine-readable cause for downstream routing.")
    message: str = Field(..., description="Human-readable explanation shown to the technician.")
    suggested_action: str = Field(
        ..., description="Escalation guidance, e.g. consult OEM or contact reliability engineer."
    )


class GuardrailReport(_SentryBase):
    """Summary of all guardrail checks run against a synthesis response (R5.4, R5.5, R5.9)."""

    passed: list[str] = Field(
        default_factory=list,
        description='Names of guardrails that passed, e.g. ["citation", "safety", "numeric"].',
    )
    failed: list[str] = Field(
        default_factory=list,
        description="Names of guardrails that failed; non-empty triggers a block or refusal.",
    )
    dropped_steps: int = Field(
        default=0,
        ge=0,
        description="Number of checklist steps dropped due to failed citation resolution (R5.4).",
    )
    notes: str = Field(
        default="",
        description="Free-text diagnostic notes from the guardrail layer for the audit log.",
    )


class ResponseMeta(_SentryBase):
    """Telemetry and provenance metadata attached to every DiagnosisResponse."""

    prompt_version: str = Field(..., description='Prompt file version tag, e.g. "v1.4.0".')
    model: str = Field(..., description="LLM model identifier as reported by the provider.")
    retriever: str = Field(
        ..., description='Retrieval configuration used, e.g. "hybrid+rerank".'
    )
    chunks_retrieved: int = Field(
        ..., ge=0, description="Number of chunks passed to the LLM context window."
    )
    latency_ms: int = Field(..., ge=0, description="End-to-end wall-clock latency in milliseconds.")
    corpus_revision: str = Field(
        ..., description="Git revision or DVC hash of the corpus at the time of retrieval."
    )


class DiagnosisResponse(_SentryBase):
    """Complete structured output of the SENTRY pipeline for one diagnostic request.

    This is the contract produced by S5 (Synthesis) and consumed by S6 (API)
    and S7 (UI).  Every field must be present; refusal is represented by a
    non-None `refusal` field, not by omitting other fields.
    """

    request_id: str = Field(..., description="Unique request identifier (ULID or UUID).")
    asset_id: str = Field(..., description="Asset identifier echoed from the request.")
    measured_facts: list[MeasuredFact] = Field(
        default_factory=list,
        description="Verbatim quantitative facts from S2; never generated by the LLM.",
    )
    manual_instructions: list[ManualInstruction] = Field(
        default_factory=list,
        description="Cited procedural steps derived from retrieved document chunks.",
    )
    inspection_checklist: list[ChecklistStep] = Field(
        default_factory=list,
        description="Ordered checklist; safety/isolation steps sort to the front in post-processing.",
    )
    hypotheses: list[Hypothesis] = Field(
        default_factory=list,
        description="Ranked probable root causes; explicitly labelled as uncertain.",
    )
    retrieval_status: Literal["sufficient", "insufficient"] = Field(
        ..., description="Echoed from RetrievalResult; 'insufficient' implies a refusal."
    )
    refusal: Refusal | None = Field(
        default=None,
        description="Populated iff the system could not produce a grounded response (R5.6).",
    )
    guardrails: GuardrailReport = Field(
        ..., description="Guardrail check outcomes for this response."
    )
    meta: ResponseMeta = Field(..., description="Telemetry and provenance for the audit log.")


