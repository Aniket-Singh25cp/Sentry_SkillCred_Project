class DiagnoseRequest(_SentryBase):
    """Incoming payload for POST /v1/diagnose.

    Sensors are keyed by sensor name; missing keys mean the sensor was not
    supplied (which is distinct from status=='missing' inside a SensorReading).
    """

    asset_id: str = Field(..., description="Asset identifier (must match a known asset).")
    captured_at: datetime = Field(
        ..., description="ISO-8601 timestamp of the sensor snapshot."
    )
    error_code: str | None = Field(
        default=None,
        description="Machine error code displayed on the HMI, if present.",
    )
    sensors: dict[str, SensorReading] = Field(
        default_factory=dict,
        description="Sensor readings keyed by sensor name.",
    )
    context: dict[str, object] = Field(
        default_factory=dict,
        description="Free-form key-value pairs from the request context (operating hours, notes, etc.).",
    )


class FeedbackRequest(_SentryBase):
    """Payload for POST /v1/feedback — stretch goal (R13 feedback loop).

    Records which checklist step resolved the fault, for reranker training data.
    """

    request_id: str = Field(..., description="The request_id of the DiagnosisResponse being rated.")
    resolved_at_step: int | None = Field(
        default=None,
        ge=1,
        description="order of the ChecklistStep that resolved the fault; None if unresolved.",
    )
    was_resolved: bool = Field(
        ..., description="True iff the fault was resolved during this diagnosis session."
    )
    comments: str = Field(
        default="",
        description="Optional free-text from the technician.",
    )
